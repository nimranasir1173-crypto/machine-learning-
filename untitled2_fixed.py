from sklearn.model_selection import train_test_split

# Split the DataFrame into 80% training and 20% testing
train_df, test_df = train_test_split(df, test_size=0.2, random_state=42)

# Display the shapes
print(f"Original dataset shape: {df.shape}")
print(f"Training dataset shape: {train_df.shape} (80%)")
print(f"Testing dataset shape: {test_df.shape} (20%)")

from sklearn.tree import DecisionTreeRegressor
from sklearn.metrics import mean_squared_error, r2_score
from sklearn.impute import SimpleImputer
import numpy as np

# Define target and features
target_col = 'Calories'
feature_cols = [
    'Total Fat (g)',
    'Trans Fat (g)',
    'Saturated Fat (g)',
    'Sodium (mg)',
    'Total Carbohydrates (g)',
    'Cholesterol (mg)',
    'Dietary Fibre (g)',
    'Sugars (g)',
    'Protein (g)',
    'Vitamin A (% DV)',
    'Vitamin C (% DV)',
    'Calcium (% DV)',
    'Iron (% DV)',
    'Caffeine (mg)'
]

# Extract features and targets from training and testing splits
X_train = train_df[feature_cols]
y_train = train_df[target_col]
X_test = test_df[feature_cols]
y_test = test_df[target_col]

# Handle missing values (e.g., in Caffeine or Total Fat) by imputing the median
imputer = SimpleImputer(strategy='median')
X_train_imputed = imputer.fit_transform(X_train)
X_test_imputed = imputer.transform(X_test)

# Initialize and train the Decision Tree Regressor
dt_model = DecisionTreeRegressor(max_depth=5, random_state=42)
dt_model.fit(X_train_imputed, y_train)

# Predict on training and testing sets
y_train_pred = dt_model.predict(X_train_imputed)
y_test_pred = dt_model.predict(X_test_imputed)

# Evaluate the model
train_rmse = np.sqrt(mean_squared_error(y_train, y_train_pred))
test_rmse = np.sqrt(mean_squared_error(y_test, y_test_pred))
train_r2 = r2_score(y_train, y_train_pred)
test_r2 = r2_score(y_test, y_test_pred)

print(f"--- Model Evaluation: Decision Tree Regressor ---")
print(f"Training RMSE: {train_rmse:.2f} calories")
print(f"Testing RMSE: {test_rmse:.2f} calories")
print(f"Training R² Score: {train_r2:.4f}")
print(f"Testing R² Score: {test_r2:.4f}")

