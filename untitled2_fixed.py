# 1. Clean column names by stripping extra spaces
df.columns = df.columns.str.strip()
print("Cleaned Column Names:", list(df.columns))

# 2. Clean and convert numeric columns
# Remove '%' and handle other string representations
cols_to_clean = [
    'Total Fat (g)',
    'Vitamin A (% DV)',
    'Vitamin C (% DV)',
    'Calcium (% DV)',
    'Iron (% DV)',
    'Caffeine (mg)'
]

for col in cols_to_clean:
    # Strip whitespace, replace percentage signs, and coerce non-numeric (like 'Varies', 'varies') to NaN
    df[col] = df[col].astype(str).str.replace('%', '', regex=False).str.strip()
    df[col] = pd.to_numeric(df[col], errors='coerce')

# Check the updated data types and missing values summary
print("\n--- Cleaned Data Types ---")
print(df[cols_to_clean].dtypes)
